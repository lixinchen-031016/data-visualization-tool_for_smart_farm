import streamlit as st

def show_instructions():
    st.title("交互式使用指南")
    
    # 第一步：数据导入引导
    with st.expander("数据导入教程"):
        st.markdown("""
        1. 点击左侧菜单栏的 **"数据概览"**
        2. 在文件上传区域点击 **"Browse files"** 选择您的文件
        3. 支持的文件格式：
           - CSV (逗号分隔值)
           - Excel (.xlsx/.xls)
           - JSON (.json)
        4. 上传后会自动显示：
           - 行数/列数统计
           - 数据预览表
           - 数据类型信息
        """)
    
    # 第二步：数据清洗引导
    with st.expander("数据清洗操作指南"):
        st.markdown("""
        1. 点击左侧菜单栏的 **"数据清洗"**
        2. 使用以下功能：
           - **删除重复行**：点击按钮即可移除完全重复的行
           - **处理缺失值**：
             1. 选择需要处理的列
             2. 选择处理方式（删除/填充平均值/中位数/众数）
           - **删除不需要的列**：
             1. 多选框选择要删除的列
             2. 点击"删除选中的列"按钮
        3. 使用交互式编辑器直接修改数据
        """)
    
    # 第三步：数据分析引导
    with st.expander("数据分析操作说明"):
        st.markdown("""
        1. 点击左侧菜单栏的 **"数据分析"**
        2. 查看描述性统计信息：
           - 计数、平均值、标准差
           - 最小/最大值、四分位数
        """)
    
    # 第四步：数据可视化引导
    with st.expander("图表创建完整指南"):
        st.markdown("""
        1. 点击左侧菜单栏的 **"可视化"**
        2. 选择图表类型：
           - 散点图：显示两个变量间关系
           - 线图：展示时间序列趋势
           - 柱状图：比较不同类别
           - 箱线图：显示分布情况
           - 直方图：展示单变量分布
           - 饼图：显示比例关系
           - 热力图：查看多变量相关性
        """)
    
    # 第五步：高级分析引导
    with st.expander("高级分析操作指引"):
        st.markdown("""
        1. 点击左侧菜单栏的 **"高级分析"**
        2. 使用分组聚合功能：
           1. 选择分组列（如产品类别）
           2. 选择聚合列（如销售额）
           3. 选择聚合函数（平均值/总和等）
        """)
    
    # 第六步：机器学习引导
    with st.expander("机器学习使用教程"):
        st.markdown("""
        1. 点击左侧菜单栏的 **"机器学习"**
        2. 设置模型参数：
           1. 选择目标变量（如销售额）
           2. 选择特征列（如价格、广告费等）
        """)
    
    # 第七步：AI数据分析引导
    with st.expander("AI数据分析使用指南"):
        st.markdown("""
        1. 点击左侧菜单栏的 **"AI数据分析"**
        2. 选择数据来源：
           - 使用已上传的数据
           - 上传新数据文件
        """)

def render_ui():
    show_instructions()